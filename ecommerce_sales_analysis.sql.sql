Business Insight:
March generated all of the recorded revenue in the dataset, indicating that the available data covers a single month of sales. 
As more months of data are collected, this report can be used to identify seasonal trends, compare month-over-month performance, 
forecast future sales, and evaluate the effectiveness of marketing campaigns or promotions. */

