The average number of products purchased per order helps the business understand customer purchasing behavior. 
If the average is relatively low, the company can increase order sizes by introducing product bundles, cross-selling complementary items, 
or offering discounts for purchasing multiple products. 
Increasing the average products per order can improve overall revenue without needing to acquire additional customers.

