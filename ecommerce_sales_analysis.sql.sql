/*Question 13: Find Inactive Customers(No Orders In The last 90 Days)*/

SELECT customers.customer_id,
       customers.customer_name,
       MAX(order_date) AS latest_order_date
FROM customers
LEFT JOIN orders
ON customers.customer_id = orders.customer_id
GROUP BY  customers.customer_name,
          customers.customer_id
HAVING MAX(order_date) < DATE_SUB(CURDATE(), INTERVAL 90 DAY);  

/*Finding: 
The analysis identifies both customers whose latest order was more than 90 days ago and 
customers who have never placed an order. 
These groups represent inactive customers requiring different engagement strategies.

Business Insight:
Customers who have never purchased may respond well to welcome offers or first-order discounts, 
while previously active customers may be encouraged to return through personalized recommendations, loyalty incentives, or reactivation campaigns. 
Segmenting these groups allows the business to create more effective marketing campaigns.*/

